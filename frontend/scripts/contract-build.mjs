import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'
import { AgentEventSchema, AgentRunSchema } from '../src/agent/events.ts'
import { contractSemantics, methodSemantics } from '../src/contracts/methods.ts'
import { CONTRACT_VERSION, ContractErrorSchema, contractSchemas } from '../src/contracts/types.ts'

const frontendRoot = fileURLToPath(new URL('../', import.meta.url))
const notice = 'Generated by scripts/contract-build.mjs from zod schemas and src/contracts/methods.ts. Do not edit.'

async function main() {
  const checkOnly = readOptions()
  const schema = buildSchema()
  const artifacts = new Map([
    ['contracts/schema.json', `${JSON.stringify(schema, null, 2)}\n`],
    ['contracts/CONTRACT.md', buildDocument(schema)],
  ])
  await emitArtifacts(artifacts, checkOnly)
  console.log(`contract${checkOnly ? ':check' : ''}: ${Object.keys(methodSemantics).length} methods, ${AgentEventSchema.options.length} events, ${artifacts.size} artifacts ${checkOnly ? 'match' : 'generated'}.`)
}

function readOptions() {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: node scripts/contract-build.mjs [--check]')
  }
  return args[0] === '--check'
}

function buildSchema() {
  const registry = z.registry()
  const ids = new Map()
  function reference(name, schema) {
    if (!ids.has(schema)) {
      ids.set(schema, name)
      registry.add(schema, { id: name })
    }
    return { $ref: `#/$defs/${ids.get(schema)}` }
  }
  for (const [name, schema] of Object.entries(contractSchemas)) reference(name, schema)
  for (const event of AgentEventSchema.options) reference(event.shape.type.value, event)
  reference('AgentEvent', AgentEventSchema)
  reference('AgentRun', AgentRunSchema)

  const methods = {}
  for (const [name, method] of Object.entries(methodSemantics)) {
    methods[name] = 'params' in method ? {
      description: method.description,
      params: reference(`${name}Params`, method.params),
      result: reference(`${name}Result`, method.result),
      error: reference('ErrorResponse', contractSemantics.errors),
    } : {
      description: method.description,
      callback: { ...method.callback, event: reference('AgentEvent', method.callback.event) },
      returns: method.returns,
    }
  }
  const { schemas } = z.toJSONSchema(registry, { uri: id => `#/$defs/${id}` })
  for (const definition of Object.values(schemas)) {
    delete definition.$schema
    delete definition.$id
  }
  const semantics = { ...contractSemantics, errors: reference('ErrorResponse', contractSemantics.errors) }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $comment: notice,
    title: `Futures-AI frontend contract ${CONTRACT_VERSION}`,
    description: '契约定义目录；按 x-methods 的引用选择参数、结果或事件 schema。AgentRun 的跨事件约束由 zod 与文字约定共同定义。',
    'x-contract-version': CONTRACT_VERSION,
    'x-semantics': semantics,
    'x-methods': methods,
    $defs: schemas,
  }
}

