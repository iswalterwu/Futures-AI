import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const frontendRoot = fileURLToPath(new URL('../', import.meta.url))
const generatedNotice = 'Generated by scripts/tokens-build.mjs from src/design/tokens.json. Do not edit.'

async function main() {
  const checkOnly = readOptions()
  const entries = await readTokens()
  const T = tokenTree(entries)
  const critical = criticalCss(entries)
  const html = await readFile(resolve(frontendRoot, 'index.html'), 'utf8')
  const artifacts = new Map([
    ['src/design/generated/tokens.css', tokensCss(entries)],
    ['src/design/generated/tokens.ts', `// ${generatedNotice}\n// Dots become nested T keys; dots and underscores become hyphens in CSS names.\nexport const T = ${JSON.stringify(T, null, 2)} as const\n`],
    ['src/design/generated/echarts-theme.json', `${JSON.stringify(echartsTheme(T), null, 2)}\n`],
    ['src/design/generated/critical.css', critical],
    ['index.html', embedCriticalCss(html, critical)],
  ])

  if (checkOnly) {
    await checkArtifacts(artifacts)
  } else {
    await writeArtifacts(artifacts)
  }
  console.log(`tokens${checkOnly ? ':check' : ''}: ${entries.length} tokens, ${artifacts.size} artifacts ${checkOnly ? 'match' : 'generated'}.`)
}

function readOptions() {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: node scripts/tokens-build.mjs [--check]')
  }
  return args[0] === '--check'
}

async function readTokens() {
  const entries = JSON.parse(await readFile(resolve(frontendRoot, 'src/design/tokens.json'), 'utf8'))
  if (!Array.isArray(entries) || entries.length === 0) {
    throw new Error('tokens.json must be a non-empty array of {name, value, source, note?}.')
  }
  const names = new Set()
  const cssNames = new Set()
  const namePattern = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/
  const sourcePattern = /^(?:design\/ui\/[^/#\s]+\.md#[^#\s]+|design\/charts\/PALETTE_DARK\.md#[^#\s]+|docs\/designUI\.md#\d+(?:\.\d+)*)$/
  for (const [index, entry] of entries.entries()) {
    if (!entry || typeof entry !== 'object' || typeof entry.name !== 'string' || !namePattern.test(entry.name)) {
      throw new Error(`tokens.json entry ${index}: name must be a dotted token path.`)
    }
    const { name, value, source, note } = entry
    if (!(typeof value === 'string' && value.trim().length > 0) && !(typeof value === 'number' && Number.isFinite(value))) {
      throw new Error(`${name}: value must be a non-empty CSS string or a finite number.`)
    }
    if (typeof source !== 'string' || !sourcePattern.test(source)) {
      throw new Error(`${name}: source must reference design/ui, PALETTE_DARK, or a designUI.md section.`)
    }
    if (note !== undefined && typeof note !== 'string') {
      throw new Error(`${name}: note must be a string.`)
    }
    if (names.has(name) || cssNames.has(cssName(name))) {
      throw new Error(`${name}: duplicate token name or CSS property.`)
    }
    names.add(name)
    cssNames.add(cssName(name))
  }
  for (const name of names) {
    const parts = name.split('.')
    parts.pop()
    while (parts.length > 0) {
      if (names.has(parts.join('.'))) {
        throw new Error(`${name}: a token value cannot also be a token group.`)
      }
      parts.pop()
    }
  }
  return entries
}

function tokenTree(entries) {
  const tree = Object.create(null)
  for (const { name, value } of entries) {
    const parts = name.split('.')
    const key = parts.pop()
    let group = tree
    for (const part of parts) {
      group[part] ??= Object.create(null)
      group = group[part]
    }
    group[key] = value
  }
  return tree
}

function cssName(name) {
  return `--fai-${name.replace(/[._]/g, '-')}`
}

function tokensCss(entries) {
  const declarations = entries.map(({ name, value }) => `  ${cssName(name)}: ${value};`).join('\n')
  return `/* ${generatedNotice} */\n:root {\n${declarations}\n}\n`
}

